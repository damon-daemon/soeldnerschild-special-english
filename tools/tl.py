"""MESSAGE.DAT translation files.

script/msg/NNN.json  Japanese dump (generated by setup.py; git-ignored): [{n, jp}]
tl/msg/NNN.txt       our English only: '@n' header line, then the English with the same control
                     tags as the Japanese (all except {n} and {a:..} in the same order), blank line.

usage: tl.py dump | show NNN [FROM TO] [--todo] [--en] | apply NNN batch.txt | check [NNN...] | size NNN... | captions [--fix] | stats
"""
import glob, json, os, re, sys

sys.path.insert(0, os.path.dirname(__file__))
import msg, vwf

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCRIPT = os.path.join(ROOT, 'script', 'msg')
TL = os.path.join(ROOT, 'tl', 'msg')
BIO, BIO_SLACK = 20, 24          # biography block; pixels allowed beyond the Japanese
MAXLINES = 3                  # lines a page (the printer wraps: tools/vwf.py)
FILL = {'a': 'Wolfgang', 'p': 'Wolfgang', 'b': '00000', 'n': '\n'}   # stand-ins when measuring: name,
                              # inserted word (spell / item?), number
PAD = re.compile(r'(\{x:00\})+$')     # the last string of a block carries the sector padding
TAG = re.compile(r'\{([a-z])(?::([0-9a-f]*))?\}')
# Ending captions: MEVENT.DAT command 39 mm ssss nn shows strings ssss.. (nn of them) one a line, scrolled
# (routine 0x8002b23c, no wrapping: window 1024 px). Mode 1 draws at x 16 beside a picture (Japanese lines
# at most 12 characters = 144 px), mode 0 at x 160 (up to 13 characters = 156 px). block: [(start, n, mode)]
CAPTIONS = {0: [(105, 5, 1), (120, 6, 1), (134, 7, 1), (156, 8, 0)], 2: [(152, 7, 1), (172, 7, 1)],
            3: [(154, 6, 0), (170, 7, 0)], 6: [(714, 6, 0)], 8: [(354, 6, 1), (371, 6, 1), (384, 7, 1)],
            9: [(347, 6, 1), (359, 7, 1), (374, 7, 1)], 10: [(355, 7, 1), (369, 6, 1), (380, 7, 1)],
            11: [(369, 7, 1), (385, 7, 1), (401, 7, 1)], 12: [(355, 7, 1), (368, 7, 1), (385, 6, 1)],
            13: [(350, 7, 1), (366, 8, 1), (384, 7, 1)],
            19: [(766, 10, 0), (788, 8, 0), (807, 7, 0), (821, 11, 0), (848, 8, 0), (867, 7, 0), (888, 11, 1),
                 (901, 6, 0)]}
CAP_W = {1: 144, 0: 156}


def cap_width(t):
    return vwf.width(TAG.sub(lambda m: FILL.get(m.group(1), '') if m.group(1) in 'apb' else '', t))


def cap_wrap(text, maxw, lines=None):
    """Lines of a caption run (tags kept; a name is measured as FILL). Each sentence starts a new line
    if the run still fits in `lines` that way."""
    if lines:
        sent = re.split(r'(?<=[.!?])\s+(?=[A-Z"\'{])', text)
        ls = sum((cap_wrap(t, maxw) for t in sent), [])
        if len(sent) > 1 and len(ls) <= lines:
            return ls
    out, line = [], ''
    for w in text.split(' '):
        if line and cap_width(line + ' ' + w) > maxw:
            out.append(line); line = w
        else:
            line = (line + ' ' + w) if line else w
    return out + [line]


def caption_limits(b):
    """{string: pixel width} for the ending-caption lines of block b."""
    return {k: CAP_W[m] for s, c, m in CAPTIONS.get(b, []) for k in range(s, s + c)}


def dump():
    d = open(os.path.join(ROOT, 'extract', 'MESSAGE.DAT'), 'rb').read()
    os.makedirs(SCRIPT, exist_ok=True)
    for bi, (o, s) in enumerate(msg.blocks(d)):
        ents = [{'n': si, 'jp': PAD.sub('{x:00}', msg.to_tagged(st))}    # no block padding
                for si, (off, st) in enumerate(msg.strings(d, o, s))]
        json.dump(ents, open(os.path.join(SCRIPT, '%03d.json' % bi), 'w'), ensure_ascii=False, indent=0)


def jp(b):
    return json.load(open(os.path.join(SCRIPT, '%03d.json' % b)))


def has_text(s):
    return bool(re.sub(r'\{[^}]*\}|\s', '', s))


def read_tl(path):
    out = {}
    if not os.path.exists(path):
        return out
    for chunk in re.split(r'^@(\d+)[^\n]*\n', open(path).read(), flags=re.M)[1:]:
        pass
    parts = re.split(r'^@(\d+)[^\n]*\n', open(path).read(), flags=re.M)
    for i in range(1, len(parts), 2):
        out[int(parts[i])] = parts[i + 1].strip('\n')
    return out


def tidy(e):
    """One entry: a line break not after {n} is a space (workers may wrap long entries)."""
    lines = [l.strip() for l in e.strip('\n').rstrip().split('\n')]
    out = e.strip('\n').split('\n')[0].rstrip()          # a leading space continues a {j} line
    for l in lines[1:]:
        out += ('\n' if out.endswith('{n}') else ' ') + l
    return out[:1] + re.sub(r'  +', ' ', out[1:])


def write_tl(b, en):
    os.makedirs(TL, exist_ok=True)
    with open(os.path.join(TL, '%03d.txt' % b), 'w') as f:
        for n in sorted(en):
            f.write('@%d\n%s\n\n' % (n, en[n]))


def ctrl(s):
    return [m.group(0) for m in TAG.finditer(s) if m.group(1) not in 'napb']   # these four may move


def names(s):
    return sorted(m.group(0) for m in TAG.finditer(s) if m.group(1) in 'apb')     # names, words, numbers by slot


JTAG = re.compile(r'\{j:([0-9a-f]{4})\}')


def joined(e, en):
    """e with each {j:xxxx} continuation replaced by string xxxx's English (as far as translated)."""
    seen = set()
    while True:
        m = JTAG.search(e)
        if not m or int(m.group(1), 16) not in en or m.group(1) in seen:
            return e
        seen.add(m.group(1))
        e = e[:m.start()] + en[int(m.group(1), 16)] + e[m.end():]


def layout(e):
    """Overfull pages of a (joined) English string: pages start at {z} and end at {g} {u} {y};
    {w} only waits. A page with a speaker line ({s:..}) has room for MAXLINES - 1 lines."""
    errs = []
    flat = e.replace('\n', '')
    for page in re.split(r'\{z\}|\{[guy](?::[0-9a-f]*)?\}', flat):
        room = MAXLINES - 1 if '{s:' in page else MAXLINES
        text = TAG.sub(lambda m: FILL.get(m.group(1), ''), page)
        ls = vwf.wrap(text)
        if len(ls) > room:
            errs.append('%d lines on a page (room for %d): %s' % (len(ls), room, ' / '.join(ls)))
    return errs


def errors(j, e, en=None, cont=False, bio=False, cap=None):
    """Problems of English e for Japanese j; en = the block's English (to follow {j:..}),
    cont = e continues another string (measured with that one, not alone); bio = block 020 (character
    biographies, wrapped by the game in their own window: as wide in pixels as the Japanese at most)."""
    errs = []
    if ctrl(j) != ctrl(e):
        errs.append('tag order differs:\n    jp %s\n    en %s' % (ctrl(j), ctrl(e)))
    if names(j) != names(e) and not cap:         # caption runs: checked over the whole run (captions)
        errs.append('{a} {p} {b} tags differ (each must appear as often as in the Japanese) jp=%s en=%s' % (names(j), names(e)))
    flat = e.replace('\n', '')
    if re.search(r' \{w\} ', flat):
        errs.append('space before and after {w} (shows a double gap): keep only the one after')
    if re.search(r'[^\s}-](\{w\})+[A-Za-z0-9"\'(]', flat):
        errs.append('no space after {w} (the text goes on in the same line): add one')
    bad = set(c for c in TAG.sub('', flat) if c not in vwf.ENC and c != '§')   # § = the game's caption mark
    if bad:
        errs.append('no glyph: %s' % ''.join(sorted(bad)))
    elif cap:
        if '\n' in TAG.sub('', flat.replace('{n}', '\n')):
            errs.append('ending caption: one line a string, no {n}')
        elif cap_width(flat) > cap:
            errs.append('ending caption %d px > %d: re-split the run (tl.py captions) or say it shorter'
                        % (cap_width(flat), cap))
    elif bio:
        jw = 12 * len(TAG.sub('', j).replace('\n', ''))
        ew = vwf.width(TAG.sub('', flat))
        if ew > jw + BIO_SLACK:
            errs.append('bio text %d px, the Japanese %d px: at most %d px, say it shorter' % (ew, jw, jw + BIO_SLACK))
    elif not cont:
        errs += layout(joined(e, en or {}))
    for m in JTAG.finditer(flat):                 # the continued string goes on in the same line
        t = int(m.group(1), 16)
        if en and t in en:
            before = flat[:m.start()]
            if before.endswith('{n}') or re.search(r'\{[guyz][^}]*\}$', before):
                continue
            b2 = re.sub(r'(\{[^}]*\})+$', '', before)
            if b2 and re.search(r'[A-Za-z0-9.,!?;:\'")]$', b2) and re.match(r'[A-Za-z0-9"\'(]', en[t]):
                errs.append('the continuation @%d must start with a space (or end this one with a hyphen)' % t)
    return errs


def targets(J):
    """String numbers that continue another string ({j:xxxx} in the Japanese)."""
    return {int(m.group(1), 16) for x in J.values() for m in JTAG.finditer(x)}


_NAMES = None


def who(j):
    """'  [l 0023=Steindorf, a 0000=Ein]': the English names of the portrait / speaker / name tags."""
    global _NAMES
    if _NAMES is None:
        import names
        _NAMES = dict(names.read('persons.txt')); _NAMES.update(names.read('roles.txt'))
        _NAMES[0x320] = '(battle: the unit speaking, set at run time)'
    seen = []
    for m in re.finditer(r'\{([lsa]):([0-9a-f]{4})\}', j):
        t = '%s %s=%s' % (m.group(1), m.group(2), _NAMES.get(int(m.group(2), 16), '?'))
        if t not in seen:
            seen.append(t)
    return '  [%s]' % ', '.join(seen) if seen else ''


def show(b, lo=0, hi=None, todo=False, en=False):
    tl = read_tl(os.path.join(TL, '%03d.txt' % b))
    for x in jp(b)[lo:hi]:
        if not has_text(x['jp']) or (todo and x['n'] in tl):
            continue
        print('@%d%s\n%s' % (x['n'], who(x['jp']), x['jp']))
        if en and x['n'] in tl:
            print('EN: ' + tl[x['n']])
        print()


def bulk(fn, blocks=None):
    """Rewrite every English entry e of the given blocks (all by default) to fn(b, n, e), under the
    apply lock (workers may be applying at the same time). Returns the number changed."""
    import fcntl
    with open(os.path.join(ROOT, 'tl', '.lock'), 'w') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        c = 0
        for f in sorted(glob.glob(os.path.join(TL, '*.txt'))):
            b = int(os.path.basename(f)[:3])
            if blocks is not None and b not in blocks:
                continue
            en = read_tl(f); new = {n: fn(b, n, e) for n, e in en.items()}
            if new != en:
                write_tl(b, new); c += sum(new[n] != en[n] for n in en)
        return c


def apply(b, batch):
    import fcntl
    with open(os.path.join(ROOT, 'tl', '.lock'), 'w') as lock:    # workers apply in parallel
        fcntl.flock(lock, fcntl.LOCK_EX)
        _apply(b, batch)


def _apply(b, batch):
    J = {x['n']: x['jp'] for x in jp(b)}
    new = {n: tidy(e) for n, e in read_tl(batch).items()}; bad = 0
    path = os.path.join(TL, '%03d.txt' % b)
    en = read_tl(path); en.update(new); T = targets(J)
    affected = set(new) | {n for n in en if n in J and any(int(m.group(1), 16) in new for m in JTAG.finditer(J[n]))}
    for n in sorted(affected):                # also the strings a changed continuation belongs to
        if n not in J:
            print('@%d: no such string' % n); bad += 1; continue
        e = en[n]
        for err in errors(J[n], e, en, n in T, b == BIO, caption_limits(b).get(n)):
            print('@%d: %s' % (n, err)); bad += 1
    if bad:
        sys.exit('%d errors; nothing applied' % bad)
    write_tl(b, en)
    print('applied %d strings to %s' % (len(new), os.path.relpath(path, ROOT)))


def check(blocks):
    bad = 0
    for b in blocks:
        J = {x['n']: x['jp'] for x in jp(b)}
        en = read_tl(os.path.join(TL, '%03d.txt' % b)); T = targets(J)
        for n, e in en.items():
            for err in errors(J[n], e, en, n in T, b == BIO, caption_limits(b).get(n)):
                print('%03d @%d: %s' % (b, n, err)); bad += 1
    print('%d errors' % bad)
    return bad


def captions(fix=False):
    """Ending-caption runs: lines needed at the run's width; fix = re-split every run that fits."""
    for b, runs in sorted(CAPTIONS.items()):
        path = os.path.join(TL, '%03d.txt' % b); en = read_tl(path); changed = False
        J = {x['n']: x['jp'] for x in jp(b)}
        for s, c, m in runs:
            text = ' '.join(en[k].replace('\n', '').replace('{x:00}', '').strip() for k in range(s, s + c))
            text = re.sub(' +', ' ', text).strip()
            if sorted(names(text)) != sorted(sum((names(J[k]) for k in range(s, s + c)), [])):
                print('%03d @%d: {a} {p} {b} tags of the run differ from the Japanese' % (b, s))
            ls = cap_wrap(text, CAP_W[m], c)
            if all(cap_width(en[k]) <= CAP_W[m] for k in range(s, s + c)):
                continue                          # fits as written
            print('%03d @%d-%d (%d lines, %d px): %d needed%s' % (b, s, s + c - 1, c, CAP_W[m], len(ls),
                                                                '  TOO LONG' if len(ls) > c else ''))
            if fix and len(ls) <= c:
                ls += [''] * (c - len(ls))
                for k, l in zip(range(s, s + c), ls):
                    new = l + '{x:00}'
                    changed |= en[k] != new; en[k] = new
        if changed:
            write_tl(b, en)


def stats():
    tot = done = 0
    for f in sorted(glob.glob(os.path.join(SCRIPT, '*.json'))):
        b = int(os.path.basename(f)[:3]); tl = read_tl(os.path.join(TL, '%03d.txt' % b))
        t = [x for x in jp(b) if has_text(x['jp'])]
        d = sum(x['n'] in tl for x in t); tot += len(t); done += d
        if d:
            print('%03d %d/%d' % (b, d, len(t)))
    print('total %d/%d text strings' % (done, tot))


if __name__ == '__main__':
    a = sys.argv[1:]
    if not a:
        sys.exit(__doc__)
    cmd = a[0]
    if cmd == 'dump':
        dump()
    elif cmd == 'show':
        r = [int(x) for x in a[2:] if x.isdigit()]
        show(int(a[1]), *(r or [0, None]), todo='--todo' in a, en='--en' in a)
    elif cmd == 'apply':
        apply(int(a[1]), a[2])
    elif cmd == 'check':
        bl = [int(x) for x in a[1:]] or [int(os.path.basename(f)[:3]) for f in glob.glob(os.path.join(TL, '*.txt'))]
        sys.exit(1 if check(sorted(bl)) else 0)
    elif cmd == 'size':
        import build
        clean = open(os.path.join(ROOT, 'extract', 'MESSAGE.DAT'), 'rb').read()
        for b in [int(x) for x in a[1:]]:
            blk = build.block(clean, b)[0]
            print('%03d: %d bytes (limit %d)%s' % (b, len(blk), build.MAXBLOCK, '  TOO BIG' if len(blk) > build.MAXBLOCK else ''))
    elif cmd == 'captions':
        captions('--fix' in a)
    elif cmd == 'stats':
        stats()
